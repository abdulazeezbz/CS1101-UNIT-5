# Packing book metadata into a single tuple
book_info = ("The Alchemist", "Paulo Coelho", 1988)

# Unpacking the tuple into separate individual variables
title, author, publication_year = book_info

# Displaying the unpacked data in an organized format
print(f"Title: {title}")
print(f"Author: {author}")
print(f"Publication Year: {publication_year}")